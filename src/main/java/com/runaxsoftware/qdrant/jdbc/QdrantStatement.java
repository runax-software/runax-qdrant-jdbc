package com.runaxsoftware.qdrant.jdbc;

import com.runaxsoftware.qdrant.jdbc.connection.QdrantConnection;
import com.runaxsoftware.qdrant.jdbc.sql.executor.ExecutionResult;
import com.runaxsoftware.qdrant.jdbc.sql.executor.Executor;
import com.runaxsoftware.qdrant.jdbc.sql.parser.Parser;
import com.runaxsoftware.qdrant.jdbc.sql.planner.Catalog;
import com.runaxsoftware.qdrant.jdbc.sql.planner.Planner;
import com.runaxsoftware.qdrant.jdbc.sql.planner.plan.Plan;

import java.sql.*;

/**
 * A statement. SQL is parsed and planned, so syntax errors and unknown names are reported, and
 * a SELECT without FROM (such as a tool's {@code SELECT 'keep alive'}) returns its row. Reading
 * collections with SQL isn't supported yet: this version of the driver lists collections and
 * their columns through {@link java.sql.DatabaseMetaData}. The statement settings tools apply
 * before running a query (maximum rows, fetch size, timeout) are accepted and kept.
 */
// TODO: move this
public final class QdrantStatement implements Statement {

    private static final String NOT_YET =
        "Reading collections with SQL isn't supported yet: this version of the driver lists "
            + "collections and their columns, and runs SELECT without FROM";

    // Until the executor reads points, a statement that names a collection stops here
    private static final Catalog NO_COLLECTIONS_YET = name -> {
        throw new SQLFeatureNotSupportedException(NOT_YET);
    };

    private final Planner planner = new Planner();
    private final Executor executor = new Executor();

    private final QdrantConnection connection;
    private boolean closed;
    private boolean closeOnCompletion;
    private boolean poolable;
    private long maxRows;
    private int maxFieldSize;
    private int fetchSize;
    private int fetchDirection = ResultSet.FETCH_FORWARD;
    private int queryTimeout;
    private SQLWarning warnings;
    private ResultSet resultSet;

    QdrantStatement(QdrantConnection connection) {
        this.connection = connection;
    }

    // Running SQL

    @Override
    public ResultSet executeQuery(String sql) throws SQLException {
        checkOpen();
        return run(sql).resultSet();
    }

    @Override
    public boolean execute(String sql) throws SQLException {
        checkOpen();
        return run(sql).hasResultSet();
    }

    @Override
    public boolean execute(String sql, int autoGeneratedKeys) throws SQLException {
        return execute(sql);
    }

    @Override
    public boolean execute(String sql, int[] columnIndexes) throws SQLException {
        return execute(sql);
    }

    @Override
    public boolean execute(String sql, String[] columnNames) throws SQLException {
        return execute(sql);
    }

    @Override
    public int executeUpdate(String sql) throws SQLException {
        checkOpen();
        plan(sql);

        // Every statement that can be planned today is a SELECT
        throw new SQLException("executeUpdate can't run a SELECT: use executeQuery or execute",
            "HY000");
    }

    @Override
    public int executeUpdate(String sql, int autoGeneratedKeys) throws SQLException {
        return executeUpdate(sql);
    }

    @Override
    public int executeUpdate(String sql, int[] columnIndexes) throws SQLException {
        return executeUpdate(sql);
    }

    @Override
    public int executeUpdate(String sql, String[] columnNames) throws SQLException {
        return executeUpdate(sql);
    }

    @Override
    public long executeLargeUpdate(String sql) throws SQLException {
        return executeUpdate(sql);
    }

    @Override
    public long executeLargeUpdate(String sql, int autoGeneratedKeys) throws SQLException {
        return executeUpdate(sql);
    }

    @Override
    public long executeLargeUpdate(String sql, int[] columnIndexes) throws SQLException {
        return executeUpdate(sql);
    }

    @Override
    public long executeLargeUpdate(String sql, String[] columnNames) throws SQLException {
        return executeUpdate(sql);
    }

    @Override
    public ResultSet getResultSet() throws SQLException {
        checkOpen();
        return resultSet;
    }

    @Override
    public int getUpdateCount() throws SQLException {
        checkOpen();
        return -1;
    }

    @Override
    public long getLargeUpdateCount() throws SQLException {
        checkOpen();
        return -1;
    }

    @Override
    public boolean getMoreResults() throws SQLException {
        return getMoreResults(Statement.CLOSE_CURRENT_RESULT);
    }

    @Override
    public boolean getMoreResults(int current) throws SQLException {
        checkOpen();

        // Every statement has a single result, so there's never a next one
        if (current == Statement.KEEP_CURRENT_RESULT) {
            resultSet = null;
        } else {
            closeResultSet();
        }

        return false;
    }

    @Override
    public ResultSet getGeneratedKeys() throws SQLException {
        throw new SQLFeatureNotSupportedException("Generated keys aren't supported");
    }

    @Override
    public void cancel() throws SQLException {
        checkOpen();
    }

    // Batches

    @Override
    public void addBatch(String sql) throws SQLException {
        throw new SQLFeatureNotSupportedException("Batches aren't supported");
    }

    @Override
    public void clearBatch() throws SQLException {
        throw new SQLFeatureNotSupportedException("Batches aren't supported");
    }

    @Override
    public int[] executeBatch() throws SQLException {
        throw new SQLFeatureNotSupportedException("Batches aren't supported");
    }

    @Override
    public long[] executeLargeBatch() throws SQLException {
        throw new SQLFeatureNotSupportedException("Batches aren't supported");
    }

    // Settings

    @Override
    public int getMaxFieldSize() throws SQLException {
        checkOpen();
        return maxFieldSize;
    }

    @Override
    public void setMaxFieldSize(int max) throws SQLException {
        checkOpen();

        if (max < 0) {
            throw new SQLException("The maximum field size can't be negative", "HY024");
        }

        maxFieldSize = max;
    }

    @Override
    public int getMaxRows() throws SQLException {
        checkOpen();
        return (int) Math.min(maxRows, Integer.MAX_VALUE);
    }

    @Override
    public void setMaxRows(int max) throws SQLException {
        setLargeMaxRows(max);
    }

    @Override
    public long getLargeMaxRows() throws SQLException {
        checkOpen();
        return maxRows;
    }

    @Override
    public void setLargeMaxRows(long max) throws SQLException {
        checkOpen();

        if (max < 0) {
            throw new SQLException("The maximum number of rows can't be negative", "HY024");
        }

        maxRows = max;
    }

    @Override
    public void setEscapeProcessing(boolean enable) throws SQLException {
        checkOpen();
    }

    @Override
    public int getQueryTimeout() throws SQLException {
        checkOpen();
        return queryTimeout;
    }

    @Override
    public void setQueryTimeout(int seconds) throws SQLException {
        checkOpen();

        if (seconds < 0) {
            throw new SQLException("The query timeout can't be negative", "HY024");
        }

        queryTimeout = seconds;
    }

    @Override
    public void setCursorName(String name) throws SQLException {
        throw new SQLFeatureNotSupportedException("Named cursors aren't supported");
    }

    @Override
    public void setFetchDirection(int direction) throws SQLException {
        checkOpen();

        if (direction != ResultSet.FETCH_FORWARD && direction != ResultSet.FETCH_REVERSE
            && direction != ResultSet.FETCH_UNKNOWN) {
            throw new SQLException("Unknown fetch direction " + direction, "HY024");
        }

        fetchDirection = direction;
    }

    @Override
    public int getFetchDirection() throws SQLException {
        checkOpen();
        return fetchDirection;
    }

    @Override
    public void setFetchSize(int rows) throws SQLException {
        checkOpen();
        if (rows < 0) {
            throw new SQLException("The fetch size can't be negative", "HY024");
        }
        fetchSize = rows;
    }

    @Override
    public int getFetchSize() throws SQLException {
        checkOpen();
        return fetchSize;
    }

    @Override
    public int getResultSetConcurrency() throws SQLException {
        checkOpen();
        return ResultSet.CONCUR_READ_ONLY;
    }

    @Override
    public int getResultSetType() throws SQLException {
        checkOpen();
        return ResultSet.TYPE_FORWARD_ONLY;
    }

    @Override
    public int getResultSetHoldability() throws SQLException {
        checkOpen();
        return ResultSet.HOLD_CURSORS_OVER_COMMIT;
    }

    @Override
    public void setPoolable(boolean poolable) throws SQLException {
        checkOpen();
        this.poolable = poolable;
    }

    @Override
    public boolean isPoolable() throws SQLException {
        checkOpen();
        return poolable;
    }

    @Override
    public void closeOnCompletion() throws SQLException {
        checkOpen();
        closeOnCompletion = true;
    }

    @Override
    public boolean isCloseOnCompletion() throws SQLException {
        checkOpen();
        return closeOnCompletion;
    }

    @Override
    public SQLWarning getWarnings() throws SQLException {
        checkOpen();
        return warnings;
    }

    @Override
    public void clearWarnings() throws SQLException {
        checkOpen();
        warnings = null;
    }

    @Override
    public Connection getConnection() throws SQLException {
        checkOpen();
        return connection;
    }

    @Override
    public void close() throws SQLException {
        if (!closed) {
            closeResultSet();
        }

        closed = true;
    }

    @Override
    public boolean isClosed() {
        return closed;
    }

    // Wrapper

    @Override
    public <T> T unwrap(Class<T> type) throws SQLException {
        if (type.isInstance(this)) {
            return type.cast(this);
        }

        throw new SQLException("Not a wrapper for " + type.getName());
    }

    @Override
    public boolean isWrapperFor(Class<?> type) {
        return type.isInstance(this);
    }

    // Runs the SQL; like every JDBC run, it first closes the result of the previous one
    private ExecutionResult run(String sql) throws SQLException {
        closeResultSet();

        ExecutionResult result = executor.execute(plan(sql), this);
        resultSet = result.resultSet();
        return result;
    }

    // Reports syntax errors and unknown names before anything is sent to Qdrant
    private Plan plan(String sql) throws SQLException {
        if (sql == null) {
            throw new SQLException("The SQL is null", "HY009");
        }

        return planner.plan(Parser.parse(sql), NO_COLLECTIONS_YET);
    }

    private void closeResultSet() throws SQLException {
        if (resultSet != null) {
            ResultSet previous = resultSet;
            resultSet = null;
            previous.close();
        }
    }

    private void checkOpen() throws SQLException {
        if (closed) {
            throw new SQLException("The statement is closed", "HY010");
        }

        connection.checkOpen();
    }
}
